// Список поддерживаемых калькулятором функций для автодополненияconst 
std::vector<std::string> MATH_FUNCTIONS = {"sin", "cos", "tan", "sqrt", "log", "exp", "abs", "pow"};
// 1. ФУНКЦИЯ ПОДСВЕТКИ СИНТАКСИСА// Разбирает строку посимвольно и возвращает красивый DOM-элемент
Element HighlightSyntax(const std::string& text_str) {
    Elements tokens;
    for (char c : text_str) {
        std::string s(1, c);
        if (std::isdigit(c) || c == '.') {
            tokens.push_back(text(s) | color(Color::LightGreen)); // Цифры - зеленые
        } else if (c == '+' || c == '-' || c == '*' || c == '/' || c == '^' || c == '=') {
            tokens.push_back(text(s) | color(Color::Red) | bold); // Операции - красные и жирные
        } else if (std::isalpha(c)) {
            tokens.push_back(text(s) | color(Color::Cyan)); // Буквы (функции) - синие
        } else if (c == '(' || c == ')') {
            tokens.push_back(text(s) | color(Color::Yellow)); // Скобки - желтые
        } else {
            tokens.push_back(text(s)); // Все остальное (пробелы) - стандартное
        }
    }
    return hbox(std::move(tokens));
}
