class NodeType; 
class Node;


/// <summary>
/// Класс Calcutator оперирует узлами расчета каждый из которых может быть:
///     = числом или
///     = функцией или
///     = бинарной/унарной операциями
/// Узел расчета это класс-наследник от класса NodeType.
/// Этот класс объявляет и реализует некоторые функции которые потом переопределяются
/// другими узлами расчета.

///     SOLID в действии
/// 
/// (S) Single responsibility. Четкое разделение на классы которые в свою очередь
///     можно разложить по разным типам. 
///         =Дероево классов с абстрактным родителем Nodetype ответтчает за тип операции и
///         	порядок работы с ней: т.е. любой объект данного дерева способен "узнать" 
//              себя в строке-выражении, получить числовое значение
///        =Набор сттруктур Node получается в процессе нарезки строки введенной пользователем
///         
/// (O) Open\Close принцип. Если возникает необхдимость расширения функциональности 
///     (сделать новую функцию (А) или расширить что-то в существующей узле (Б
///     то в случае (А) нужно просто создать еще одного наследника Nodetype  а в случае (Б)
///     наследовать от уже существующего узла и перекрыть его новым методом
/// 	добавляя свою йункционаьность.Т.о. уже написанный код не меняется
///     Классы закрыты для изменения, и открыты для расширения.
///
/// (L) принцип подстановки Liskov тесно связан с Инверсией зависимостей (ИЗ) :
///     любой наследник абстракции NodeType расширяет возможности этого класса путем наследования.
///     Любой потомок может быть передан любой функции через ссылку типа NodeType
///
/// (I) С точки зрения SOLID реализуется Инверсия зависомостей (ИЗ): 
///     Calculator - класс верхнего уровня (1) работает с классами нижнего уровня (2) Node, Nodetype это
///		(конрктные узлы расчета - числами, функциями,операциями)
///     чтобы исключить зависимость (1) от (2) введен абстрактный класс NodeType
///     c методами которого и работает (1). Т.о. (1) не зависит от деталей реализации  (2)
///     а оба уровня (1) и (2) зависят от абстрации (nodetype).
/// 
/// (I) Принцип разделения интерфейса (interface segregation principle / ISP)    
///     
/// 
/// </summary>

using OperandType = long double;

class Calculator
{
    //вектор узлов расчета на основании которых Парсер калькулятора ведет разбор
    // фомируется в конструкторе Калькулятора
    std::vector<std::unique_ptr<NodeType>> nodetypes{};
    //вектор узлов, формируется методом ToReversePolishNotation (парсером) из введенноой строки
    std::vector<std::unique_ptr<Node>> vec{};
protected:
public:
    Calculator();
    std::unique_ptr<Node> 
    SliceNextNode(
            //распознаваемая подстрока
            const std::string& str,
            //предыдущий узел
            //std::unique_ptr<Node> prevnode
            //Node* prevnode
            const Node& prevnode
    ) const;
    void CheckResult(OperandType result);
    void ShowHelp();
    //в обратную польскую нотацию (ОПН)
    void ToReversePolishNotation(std::string& str);
    size_t getRpnSize() { return vec.size(); }
    //Вычисление конечного результата из ОПН лежащей в векторе vector<Node*> vec;
    OperandType Execute();
};


